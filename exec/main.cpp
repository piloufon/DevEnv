static inline void gf_multiply_scalar(const uint8_t* in, const uint8_t* h, uint8_t* out) {
    uint8_t Z[16] = {};
    uint8_t V[16];
    std::memcpy(V, in, 16);

    for (int i = 0; i < 16; ++i) {
        for (int bit = 7; bit >= 0; --bit) {
            if ((h[i] >> bit) & 1) {
                for (int k = 0; k < 16; ++k)
                    Z[k] ^= V[k];
            }

            uint8_t carry = V[15] & 1;
            for (int k = 15; k > 0; --k)
                V[k] = (V[k] >> 1) | (V[k - 1] << 7);
            V[0] >>= 1;
            if (carry)
                V[0] ^= 0xe1;
        }
    }
    std::memcpy(out, Z, 16);
}
static inline void gf_multiply_clmul(const uint8_t* in, const uint8_t* h, uint8_t* out) {
    __asm__ volatile (
        // Using Karatsuba method
        "movdqu (%[p_in]), %%xmm0\n\t"
        "movdqu (%[p_h]), %%xmm1\n\t"

        "movdqa %%xmm0, %%xmm2\n\t"
        "pclmulqdq $0x00, %%xmm1, %%xmm2\n\t"   // A0B0
        "movdqa %%xmm0, %%xmm3\n\t"
        "pclmulqdq $0x11, %%xmm1, %%xmm3\n\t"

        // A0 ^ A1
        "movdqa %%xmm0, %%xmm4\n\t"
        "psrldq $8, %%xmm4\n\t"
        "pxor %%xmm0, %%xmm4\n\t"

        // B0 ^ B1
        "movdqa %%xmm1, %%xmm5\n\t"
        "psrldq $8, %%xmm5\n\t"
        "pxor %%xmm1, %%xmm5\n\t"


        "pclmulqdq $0x00, %%xmm5, %%xmm4\n\t"

        "pxor %%xmm2, %%xmm4\n\t"
        "pxor %%xmm3, %%xmm4\n\t"

        "movdqa %%xmm4, %%xmm5\n\t"
        "pslldq $8, %%xmm5\n\t"
        "psrldq $8, %%xmm4\n\t"

        "pxor %%xmm4, %%xmm3\n\t"
        "pxor %%xmm5, %%xmm2\n\t"

        "movdqa %%xmm2, %%xmm4\n\t"
        "psrld $31, %%xmm4\n\t"
        "movdqa %%xmm3, %%xmm5\n\t"
        "psrld $31, %%xmm5\n\t"
        "pslld $1, %%xmm2\n\t"
        "pslld $1, %%xmm3\n\t"
        "movdqa %%xmm4, %%xmm7\n\t"
        "psrldq $12, %%xmm7\n\t"
        "pslldq $4, %%xmm4\n\t"
        "pslldq $4, %%xmm5\n\t"
        "por %%xmm4, %%xmm2\n\t"
        "por %%xmm5, %%xmm3\n\t"
        "por %%xmm7, %%xmm3\n\t"

        "movdqa %%xmm2, %%xmm4\n\t"
        "pslld $31, %%xmm4\n\t"
        "movdqa %%xmm2, %%xmm5\n\t"
        "pslld $30, %%xmm5\n\t"
        "movdqa %%xmm2, %%xmm6\n\t"
        "pslld $25, %%xmm6\n\t"
        "pxor %%xmm5, %%xmm4\n\t"
        "pxor %%xmm6, %%xmm4\n\t"
        "movdqa %%xmm4, %%xmm5\n\t"
        "psrldq $4, %%xmm5\n\t"
        "pslldq $12, %%xmm4\n\t"
        "pxor %%xmm4, %%xmm2\n\t"

        "movdqa %%xmm2, %%xmm6\n\t"
        "psrld $1, %%xmm6\n\t"
        "movdqa %%xmm2, %%xmm7\n\t"
        "psrld $2, %%xmm7\n\t"
        "movdqa %%xmm2, %%xmm4\n\t"
        "psrld $7, %%xmm4\n\t"
        "pxor %%xmm7, %%xmm6\n\t"
        "pxor %%xmm4, %%xmm6\n\t"
        "pxor %%xmm5, %%xmm6\n\t"
        "pxor %%xmm2, %%xmm6\n\t"
        "pxor %%xmm3, %%xmm6\n\t"

        "movdqu %%xmm6, (%[p_out])\n\t"

        : [p_in] "+r"(in), [p_h] "+r"(h), [p_out] "+r"(out)
        :
        : "xmm0", "xmm1", "xmm2", "xmm3", "xmm4", "xmm5", "xmm6", "xmm7",
        "memory", "cc"
        );
}
static inline void gf_multiply_batch4_clmul(const uint8_t* in, const uint8_t* hpowers, uint8_t* out) {
    __asm__ volatile (
        "pxor %%xmm0, %%xmm0\n\t"
        "pxor %%xmm1, %%xmm1\n\t"

        "movdqu   0(%[p_in]), %%xmm2\n\t"
        "movdqu   0(%[p_hp]),  %%xmm3\n\t"
        "movdqa %%xmm2, %%xmm6\n\t"
        "pclmulqdq $0x00, %%xmm3, %%xmm6\n\t"
        "movdqa %%xmm2, %%xmm7\n\t"
        "pclmulqdq $0x11, %%xmm3, %%xmm7\n\t"
        "movdqa %%xmm2, %%xmm8\n\t"
        "psrldq $8, %%xmm8\n\t"
        "pxor %%xmm8, %%xmm2\n\t"
        "movdqa %%xmm3, %%xmm8\n\t"
        "psrldq $8, %%xmm8\n\t"
        "pxor %%xmm8, %%xmm3\n\t"
        "pclmulqdq $0x00, %%xmm3, %%xmm2\n\t"
        "pxor %%xmm6, %%xmm2\n\t"
        "pxor %%xmm7, %%xmm2\n\t"
        "movdqa %%xmm2, %%xmm8\n\t"
        "pslldq $8, %%xmm8\n\t"
        "psrldq $8, %%xmm2\n\t"
        "pxor %%xmm8, %%xmm6\n\t"
        "pxor %%xmm2, %%xmm7\n\t"

        "movdqu  16(%[p_in]), %%xmm4\n\t"
        "movdqu  16(%[p_hp]),  %%xmm5\n\t"
        "movdqa %%xmm4, %%xmm10\n\t"
        "pclmulqdq $0x00, %%xmm5, %%xmm10\n\t"
        "movdqa %%xmm4, %%xmm11\n\t"
        "pclmulqdq $0x11, %%xmm5, %%xmm11\n\t"
        "movdqa %%xmm4, %%xmm12\n\t"
        "psrldq $8, %%xmm12\n\t"
        "pxor %%xmm12, %%xmm4\n\t"
        "movdqa %%xmm5, %%xmm12\n\t"
        "psrldq $8, %%xmm12\n\t"
        "pxor %%xmm12, %%xmm5\n\t"
        "pclmulqdq $0x00, %%xmm5, %%xmm4\n\t"
        "pxor %%xmm10, %%xmm4\n\t"
        "pxor %%xmm11, %%xmm4\n\t"
        "movdqa %%xmm4, %%xmm12\n\t"
        "pslldq $8, %%xmm12\n\t"
        "psrldq $8, %%xmm4\n\t"
        "pxor %%xmm12, %%xmm10\n\t"
        "pxor %%xmm4, %%xmm11\n\t"

        "pxor %%xmm6, %%xmm0\n\t"
        "pxor %%xmm10, %%xmm0\n\t"
        "pxor %%xmm7, %%xmm1\n\t"
        "pxor %%xmm11, %%xmm1\n\t"


        "movdqu  32(%[p_in]), %%xmm2\n\t"
        "movdqu  32(%[p_hp]),  %%xmm3\n\t"
        "movdqa %%xmm2, %%xmm6\n\t"
        "pclmulqdq $0x00, %%xmm3, %%xmm6\n\t"
        "movdqa %%xmm2, %%xmm7\n\t"
        "pclmulqdq $0x11, %%xmm3, %%xmm7\n\t"
        "movdqa %%xmm2, %%xmm8\n\t"
        "psrldq $8, %%xmm8\n\t"
        "pxor %%xmm8, %%xmm2\n\t"
        "movdqa %%xmm3, %%xmm8\n\t"
        "psrldq $8, %%xmm8\n\t"
        "pxor %%xmm8, %%xmm3\n\t"
        "pclmulqdq $0x00, %%xmm3, %%xmm2\n\t"
        "pxor %%xmm6, %%xmm2\n\t"
        "pxor %%xmm7, %%xmm2\n\t"
        "movdqa %%xmm2, %%xmm8\n\t"
        "pslldq $8, %%xmm8\n\t"
        "psrldq $8, %%xmm2\n\t"
        "pxor %%xmm8, %%xmm6\n\t"
        "pxor %%xmm2, %%xmm7\n\t"

        "movdqu  48(%[p_in]), %%xmm4\n\t"
        "movdqu  48(%[p_hp]),  %%xmm5\n\t"
        "movdqa %%xmm4, %%xmm10\n\t"
        "pclmulqdq $0x00, %%xmm5, %%xmm10\n\t"
        "movdqa %%xmm4, %%xmm11\n\t"
        "pclmulqdq $0x11, %%xmm5, %%xmm11\n\t"
        "movdqa %%xmm4, %%xmm12\n\t"
        "psrldq $8, %%xmm12\n\t"
        "pxor %%xmm12, %%xmm4\n\t"
        "movdqa %%xmm5, %%xmm12\n\t"
        "psrldq $8, %%xmm12\n\t"
        "pxor %%xmm12, %%xmm5\n\t"
        "pclmulqdq $0x00, %%xmm5, %%xmm4\n\t"
        "pxor %%xmm10, %%xmm4\n\t"
        "pxor %%xmm11, %%xmm4\n\t"
        "movdqa %%xmm4, %%xmm12\n\t"
        "pslldq $8, %%xmm12\n\t"
        "psrldq $8, %%xmm4\n\t"
        "pxor %%xmm12, %%xmm10\n\t"
        "pxor %%xmm4, %%xmm11\n\t"

        "pxor %%xmm6, %%xmm0\n\t"
        "pxor %%xmm10, %%xmm0\n\t"
        "pxor %%xmm7, %%xmm1\n\t"
        "pxor %%xmm11, %%xmm1\n\t"

        // Reduction
        "movdqa %%xmm0, %%xmm2\n\t"
        "movdqa %%xmm1, %%xmm3\n\t"

        "movdqa %%xmm2, %%xmm4\n\t"
        "psrld $31, %%xmm4\n\t"
        "movdqa %%xmm3, %%xmm5\n\t"
        "psrld $31, %%xmm5\n\t"
        "pslld $1, %%xmm2\n\t"
        "pslld $1, %%xmm3\n\t"
        "movdqa %%xmm4, %%xmm7\n\t"
        "psrldq $12, %%xmm7\n\t"
        "pslldq $4, %%xmm4\n\t"
        "pslldq $4, %%xmm5\n\t"
        "por %%xmm4, %%xmm2\n\t"
        "por %%xmm5, %%xmm3\n\t"
        "por %%xmm7, %%xmm3\n\t"

        "movdqa %%xmm2, %%xmm4\n\t"
        "pslld $31, %%xmm4\n\t"
        "movdqa %%xmm2, %%xmm5\n\t"
        "pslld $30, %%xmm5\n\t"
        "movdqa %%xmm2, %%xmm6\n\t"
        "pslld $25, %%xmm6\n\t"
        "pxor %%xmm5, %%xmm4\n\t"
        "pxor %%xmm6, %%xmm4\n\t"
        "movdqa %%xmm4, %%xmm5\n\t"
        "psrldq $4, %%xmm5\n\t"
        "pslldq $12, %%xmm4\n\t"
        "pxor %%xmm4, %%xmm2\n\t"

        "movdqa %%xmm2, %%xmm6\n\t"
        "psrld $1, %%xmm6\n\t"
        "movdqa %%xmm2, %%xmm7\n\t"
        "psrld $2, %%xmm7\n\t"
        "movdqa %%xmm2, %%xmm4\n\t"
        "psrld $7, %%xmm4\n\t"
        "pxor %%xmm7, %%xmm6\n\t"
        "pxor %%xmm4, %%xmm6\n\t"
        "pxor %%xmm5, %%xmm6\n\t"
        "pxor %%xmm2, %%xmm6\n\t"
        "pxor %%xmm3, %%xmm6\n\t"

        "movdqu %%xmm6, (%[p_out])\n\t"

        : [p_in] "+r"(in), [p_hp] "+r"(hpowers), [p_out] "+r"(out)
        :
        : "xmm0", "xmm1", "xmm2", "xmm3", "xmm4", "xmm5", "xmm6", "xmm7",
        "xmm8", "xmm10", "xmm11", "xmm12",
        "memory", "cc"
        );
}


