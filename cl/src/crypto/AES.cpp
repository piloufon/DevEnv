constexpr uint8_t xtime_forward(uint8_t x) {
    return (x << 1) ^ (((x >> 7) & 1) * 0x1b);
}
void sub_bytes(std::span<uint8_t, 16> block) {
    for (uint8_t i = 0; i < 16; i++) {
        block[i] = sbox[block[i]];
    }
}
void sub_bytes_inv(std::span<uint8_t, 16> block) {
    for (uint8_t i = 0; i < 16; i++) {
        block[i] = sboxinv[block[i]];
    }
}
void shift_rows(std::span<uint8_t, 16> block) {
    unsigned char i, j, k, l;

    i = block[1];
    block[1] = block[5];
    block[5] = block[9];
    block[9] = block[13];
    block[13] = i;

    j = block[10];
    block[10] = block[2];
    block[2] = j;

    k = block[3];
    block[3] = block[15];
    block[15] = block[11];
    block[11] = block[7];
    block[7] = k;

    l = block[14];
    block[14] = block[6];
    block[6] = l;
}
void shift_rows_inv(std::span<uint8_t, 16> block) {
    unsigned char i, j, k, l;

    i = block[1];
    block[1] = block[13];
    block[13] = block[9];
    block[9] = block[5];
    block[5] = i;

    j = block[2];
    block[2] = block[10];
    block[10] = j;

    k = block[3];
    block[3] = block[7];
    block[7] = block[11];
    block[11] = block[15];
    block[15] = k;

    l = block[6];
    block[6] = block[14];
    block[14] = l;
}
void mix_columns(std::span<uint8_t, 16> block) {
    unsigned char i, a, b, c, d, e;

    for (i = 0; i < 16; i += 4) {
        a = block[i];
        b = block[i + 1];
        c = block[i + 2];
        d = block[i + 3];

        e = a ^ b ^ c ^ d;

        block[i] ^= e ^ rj_xtime(a ^ b);
        block[i + 1] ^= e ^ rj_xtime(b ^ c);
        block[i + 2] ^= e ^ rj_xtime(c ^ d);
        block[i + 3] ^= e ^ rj_xtime(d ^ a);
    }
}
void mix_columns_inv(std::span<uint8_t, 16> block) {
    unsigned char i, a, b, c, d, e, x, y, z;

    for (i = 0; i < 16; i += 4) {
        a = block[i];
        b = block[i + 1];
        c = block[i + 2];
        d = block[i + 3];

        e = a ^ b ^ c ^ d;
        z = rj_xtime(e);
        x = e ^ rj_xtime(rj_xtime(z ^ a ^ c));  y = e ^ rj_xtime(rj_xtime(z ^ b ^ d));

        block[i] ^= x ^ rj_xtime(a ^ b);
        block[i + 1] ^= y ^ rj_xtime(b ^ c);
        block[i + 2] ^= x ^ rj_xtime(c ^ d);
        block[i + 3] ^= y ^ rj_xtime(d ^ a);
    }
}

template<size_t N>
    requires(N == 128 || N == 192 || N == 256)
inline void AES<N>::m_encrypt(std::span<uint8_t, 16> block) {
    add_round_key(block, 0);

    for (size_t round = 1; round < NR; ++round) {
        sub_bytes(block);
        shift_rows(block);
        mix_columns(block);
        add_round_key(block, round);
    }

    sub_bytes(block);
    shift_rows(block);
    add_round_key(block, NR);
}

template<size_t N>
    requires(N == 128 || N == 192 || N == 256)
void AES<N>::m_decrypt(std::span<uint8_t, 16> block) {
    add_round_key(block, NR);

    for (size_t round = NR - 1; round >= 1; --round) {
        shift_rows_inv(block);
        sub_bytes_inv(block);
        add_round_key(block, round);
        mix_columns_inv(block);
    }

    shift_rows_inv(block);
    sub_bytes_inv(block);
    add_round_key(block, 0);
}

template<size_t N>
    requires(N == 128 || N == 192 || N == 256)
void AES<N>::key_expansion(const Key& key) {
    auto sub_word = [](uint32_t w) -> uint32_t { // Required for template
        return (uint32_t(sbox[(w >> 24) & 0xFF]) << 24)
            | (uint32_t(sbox[(w >> 16) & 0xFF]) << 16)
            | (uint32_t(sbox[(w >> 8) & 0xFF]) << 8)
            | (uint32_t(sbox[(w) & 0xFF]));
        };

    auto rot_word = [](uint32_t w) -> uint32_t { // Required for template
        return (w << 8) | (w >> 24);
        };

    uint32_t W[EXP_KEY_WORDS];

    for (size_t i = 0; i < NK; ++i) {
        W[i] = (uint32_t(key[4 * i]) << 24)
            | (uint32_t(key[4 * i + 1]) << 16)
            | (uint32_t(key[4 * i + 2]) << 8)
            | (uint32_t(key[4 * i + 3]));
    }

    uint8_t rcon = 0x01;

    for (size_t i = NK; i < EXP_KEY_WORDS; ++i) {
        uint32_t temp = W[i - 1];

        if (i % NK == 0) {
            temp = sub_word(rot_word(temp)) ^ (uint32_t(rcon) << 24);
            rcon = xtime_forward(rcon);
        }
        // AES-256 only
        else if constexpr (NK == 8) {
            if (i % NK == 4)
                temp = sub_word(temp);
        }

        W[i] = W[i - NK] ^ temp;
    }

    for (size_t i = 0; i < EXP_KEY_WORDS; ++i) {
        m_rkey[4 * i] = (W[i] >> 24) & 0xFF;
        m_rkey[4 * i + 1] = (W[i] >> 16) & 0xFF;
        m_rkey[4 * i + 2] = (W[i] >> 8) & 0xFF;
        m_rkey[4 * i + 3] = (W[i]) & 0xFF;
    }
}

template<size_t N>
    requires(N == 128 || N == 192 || N == 256)
void AES<N>::add_round_key(std::span<uint8_t, 16> block, size_t round) {
    size_t offset = round * 16;
    for (size_t i = 0; i < 16; ++i)
        block[i] ^= m_rkey[offset + i];
}

template<size_t N>
    requires(N == 128 || N == 192 || N == 256)
void AES<N>::encrypt(std::span<const uint8_t> in, std::vector<uint8_t>& out) {
    size_t numBlocks = in.size() / 16;
    size_t remainder = in.size() % 16;

    out.resize(numBlocks * 16 + (remainder ? 16 : 0));

    for (size_t i = 0; i < numBlocks; ++i) {
        std::array<uint8_t, 16> block;
        std::memcpy(block.data(), in.data() + i * 16, 16);
        m_encrypt(block);
        std::memcpy(out.data() + i * 16, block.data(), 16);
    }

    if (remainder) {
        std::array<uint8_t, 16> block = { 0 };
        uint8_t padValue = static_cast<uint8_t>(16 - remainder);
        std::memcpy(block.data(), in.data() + numBlocks * 16, remainder);
        std::memset(block.data() + remainder, padValue, 16 - remainder);
        m_encrypt(block);
        std::memcpy(out.data() + numBlocks * 16, block.data(), 16);
    }
}

template<size_t N>
    requires(N == 128 || N == 192 || N == 256)
bool AES<N>::decrypt(std::span<const uint8_t> in, std::vector<uint8_t>& out) {
    if (in.size() == 0 || in.size() % 16 != 0)
        return false;

    size_t numBlocks = in.size() / 16;
    out.resize(in.size());

    for (size_t i = 0; i < numBlocks; ++i) {
        std::array<uint8_t, 16> block;
        std::memcpy(block.data(), in.data() + i * 16, 16);
        m_decrypt(block);
        std::memcpy(out.data() + i * 16, block.data(), 16);
    }


    uint8_t padValue = out.back();
    if (padValue == 0 || padValue > 16)
        return false;

    for (size_t i = out.size() - padValue; i < out.size(); ++i) {
        if (out[i] != padValue)
            return false;
    }

    out.resize(out.size() - padValue);
    return true;
}

